@pytest.fixture(scope="module")
def libreoffice_info():
    return find_libreoffice()


@pytest.fixture(scope="module")
def lo_profile(tmp_path_factory):
    """A private LibreOffice profile so test runs never fight the user's one."""
    return tmp_path_factory.mktemp("lo_profile")


def convert_with_libreoffice(source: Path, target: Path, libreoffice_info, profile: Path) -> Path:
    """Convert ``source`` (modern) into the legacy format at ``target``."""
    target.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            str(libreoffice_info.executable),
            "--headless",
            f"-env:UserInstallation=file://{profile}",
            "--convert-to", target.suffix[1:],
            "--outdir", str(target.parent),
            str(source),
        ],
        capture_output=True,
        text=True,
        check=True,
        timeout=300,
    )
    assert target.is_file() and target.stat().st_size > 0
    return target


@pytest.fixture(scope="module")
def legacy_fixtures(tmp_path_factory, libreoffice_info, lo_profile):
    """Real .doc / .ppt / .xls files, generated once and shared by the tests.

    Modern files are built with the same libraries the v2 extractors use, then
    converted BACK to the legacy format with LibreOffice so the pipeline under
    test converts genuine OLE2 documents.
    """
    root = tmp_path_factory.mktemp("legacy_sources")
    modern_root = root / "modern"
    make_docx(modern_root / "Lab Work.docx")
    make_pptx(modern_root / "Lecture Deck.pptx")
    make_xlsx(modern_root / "Spreadsheet Data.xlsx")

    legacy_root = root / "legacy"
    return {
        "doc": convert_with_libreoffice(
            modern_root / "Lab Work.docx",
            legacy_root / "Lab Work.doc",
            libreoffice_info,
            lo_profile,
        ),
        "ppt": convert_with_libreoffice(
            modern_root / "Lecture Deck.pptx",
            legacy_root / "Lecture Deck.ppt",
            libreoffice_info,
            lo_profile,
        ),
        "xls": convert_with_libreoffice(
            modern_root / "Spreadsheet Data.xlsx",
            legacy_root / "Spreadsheet Data.xls",
            libreoffice_info,
            lo_profile,
        ),
    }


def make_legacy_repo(tmp_path, legacy_fixtures):
    """A course containing one .doc, one .ppt, one .xls, one modern .docx and
    one unsupported .txt file."""
    raw = tmp_path / "raw" / COURSE_ID
    for relative, fixture in (
        ("Week 5/Lab Work.doc", legacy_fixtures["doc"]),
        ("Week 6/Lecture Deck.ppt", legacy_fixtures["ppt"]),
        ("Week 3/Spreadsheet Data.xls", legacy_fixtures["xls"]),
    ):
        target = raw / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(fixture, target)
    make_docx(raw / "Week 9" / "Boundary Value Analysis.docx")
    (raw / "Week 10" / "Notes.txt").parent.mkdir(parents=True, exist_ok=True)
    (raw / "Week 10" / "Notes.txt").write_text("plain text notes", encoding="utf-8")

    documents = [
        doc_record("Week 3/Spreadsheet Data.xls", mime_type="application/vnd.ms-excel"),
        doc_record("Week 5/Lab Work.doc", mime_type="application/msword"),
        doc_record("Week 6/Lecture Deck.ppt", mime_type="application/vnd.ms-powerpoint"),
        doc_record("Week 9/Boundary Value Analysis.docx", status="pending"),
        doc_record("Week 10/Notes.txt", status="pending"),
    ]
    write_inventory(tmp_path, documents)
    write_registry(tmp_path, [COURSE_ID])
    return tmp_path


def v2_json(data_root: Path, relative_path: str) -> dict:
    out = data_root / "extracted_v2" / COURSE_ID / Path(relative_path).with_suffix(".json")
    return json.loads(out.read_text("utf-8"))


def raw_bytes(data_root: Path, relative_path: str) -> bytes:
    return (data_root / "raw" / COURSE_ID / relative_path).read_bytes()


