def test_doc_extracts_via_docx_extractor(tmp_path, legacy_fixtures):
    repo = make_legacy_repo(tmp_path, legacy_fixtures)
    assert run_extraction(COURSE_ID, data_root=repo) == 0

    result = v2_json(repo, "Week 5/Lab Work.doc")
    assert result["document"]["filename"] == "Lab Work.doc"
    assert result["document"]["relative_path"] == "Week 5/Lab Work.doc"
    assert result["source"] == {
        "format": "doc",
        "mime_type": "application/msword",
        "extension": ".doc",
        "extraction_format": "docx",
    }
    assert result["conversion"] == {
        "performed": True,
        "tool": "LibreOffice",
        "source_format": ".doc",
        "target_format": ".docx",
        "status": "success",
    }
    assert result["extraction"]["extractor"] == "docx_extractorv2"
    assert result["extraction"]["method"] == "python-docx"
    assert result["extraction"]["status"] == "success"

    # real content survived the round-trip through LibreOffice
    headings = [p["text"] for p in result["content"]["paragraphs"] if p["type"] == "heading"]
    assert "Test Case Design" in headings
    assert "Equivalence Partitioning" in headings


