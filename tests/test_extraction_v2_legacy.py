# --------------------------------------------------------------------------- #
# conversion failure — fail safely, keep going
# --------------------------------------------------------------------------- #
def test_corrupt_doc_fails_safely_and_batch_continues(tmp_path, legacy_fixtures):
    repo = make_legacy_repo(tmp_path, legacy_fixtures)
    broken = repo / "raw" / COURSE_ID / "Week 11" / "Broken Lab.doc"
    broken.parent.mkdir(parents=True, exist_ok=True)
    broken.write_bytes(legacy_fixtures["doc"].read_bytes()[:64])  # truncated OLE header
    broken_before = broken.read_bytes()

    # register the broken document too
    inv_path = repo / "inventories" / COURSE_ID / "file_inventory.json"
    inventory = json.loads(inv_path.read_text("utf-8"))
    inventory["documents"].append(
        doc_record("Week 11/Broken Lab.doc", mime_type="application/msword")
    )
    inv_path.write_text(json.dumps(inventory), encoding="utf-8")

    output = run_extraction(COURSE_ID, data_root=repo)
    assert output == 0  # a failed conversion must never abort the course run

    # the broken document: no output written (stays eligible for retry), error reported
    assert not (repo / "extracted_v2" / COURSE_ID / "Week 11").exists()
    assert broken.read_bytes() == broken_before

    # ...but the healthy documents in the same run were still extracted
    assert (repo / "extracted_v2" / COURSE_ID / "Week 5" / "Lab Work.json").is_file()
    assert (repo / "extracted_v2" / COURSE_ID / "Week 6" / "Lecture Deck.json").is_file()
    assert (repo / "extracted_v2" / COURSE_ID / "Week 3" / "Spreadsheet Data.json").is_file()


def test_missing_libreoffice_fails_legacy_but_extracts_modern(tmp_path, legacy_fixtures, monkeypatch):
    repo = make_legacy_repo(tmp_path, legacy_fixtures)
    # Simulate an environment without LibreOffice: both the orchestrator's
    # up-front probe and the converter's require_libreoffice() must see None.
    monkeypatch.setattr("extraction_orchestratorv2.find_libreoffice", lambda: None)
    monkeypatch.setattr("legacy_conversion.find_libreoffice", lambda: None)

    assert run_extraction(COURSE_ID, data_root=repo) == 0

    # legacy documents are reported as conversion failures, no output written
    assert not (repo / "extracted_v2" / COURSE_ID / "Week 5").exists()
    assert not (repo / "extracted_v2" / COURSE_ID / "Week 6").exists()
    assert not (repo / "extracted_v2" / COURSE_ID / "Week 3").exists()
    # the modern document still extracts
    assert (repo / "extracted_v2" / COURSE_ID / "Week 9" / "Boundary Value Analysis.json").is_file()


