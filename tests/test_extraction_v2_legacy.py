def test_dry_run_plans_legacy_conversion_without_writing(tmp_path, legacy_fixtures, capsys):
    repo = make_legacy_repo(tmp_path, legacy_fixtures)
    assert run_extraction(COURSE_ID, data_root=repo, dry_run=True) == 0

    output = capsys.readouterr().out
