def test_legacy_format_registry_targets_modern_equivalents():
    assert set(LEGACY_FORMATS) == {".doc", ".ppt", ".xls"}
    assert LEGACY_FORMATS[".doc"].target_extension == ".docx"
    assert LEGACY_FORMATS[".ppt"].target_extension == ".pptx"
    assert LEGACY_FORMATS[".xls"].target_extension == ".xlsx"
    assert MIME_TO_LEGACY["application/msword"] == ".doc"
    assert MIME_TO_LEGACY["application/vnd.ms-powerpoint"] == ".ppt"
    assert MIME_TO_LEGACY["application/vnd.ms-excel"] == ".xls"


def test_route_document_legacy_by_extension():
    kind, key = _route_document(doc_record("Week 5/Lab Work.doc"))
    assert kind == "legacy" and key == ".doc"

    kind, key = _route_document(doc_record("Week 6/Deck.ppt"))
    assert kind == "legacy" and key == ".ppt"

    kind, key = _route_document(doc_record("Week 3/Sheet.xls"))
    assert kind == "legacy" and key == ".xls"


def test_route_document_mime_fallback_when_extension_missing():
    doc = doc_record("Week 5/Unknown", mime_type="application/msword")
    assert doc["extension"] is None
    kind, key = _route_document(doc)
    assert kind == "legacy" and key == ".doc"

    doc = doc_record("General/Unknown", mime_type="application/pdf")
    assert doc["extension"] is None
    kind, key = _route_document(doc)
    assert kind == "modern" and key == ".pdf"


