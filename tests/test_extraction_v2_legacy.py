# temporary conversion directory lifecycle
# --------------------------------------------------------------------------- #
def test_conversion_tmp_dir_cleaned_up(tmp_path, legacy_fixtures, monkeypatch):
    repo = make_legacy_repo(tmp_path, legacy_fixtures)

    captured: list[Path] = []

    def fake_mkdtemp(*args, **kwargs):
        path = Path(tmp_path) / "conversion_tmp"
        path.mkdir(parents=True, exist_ok=True)
        captured.append(path)
        return str(path)

    monkeypatch.setattr(tempfile, "mkdtemp", fake_mkdtemp)
    assert run_extraction(COURSE_ID, data_root=repo) == 0

    assert captured, "the orchestrator should have created a conversion temp dir"
    assert not captured[0].exists(), "the conversion temp dir must be cleaned up"
    # the temp dir never lived inside the raw course tree
    assert not str(captured[0]).startswith(str(repo / "raw"))


