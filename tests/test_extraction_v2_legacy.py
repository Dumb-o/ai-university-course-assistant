"""Tests for v2 legacy Microsoft Office handling (DOC / PPT / XLS via LibreOffice).

Real legacy files are generated by converting freshly-built modern files BACK
to the legacy format with LibreOffice (docx→doc, pptx→ppt, xlsx→xls), so the
conversion under test runs against genuine OLE2 containers rather than fake
bytes. The whole module skips when LibreOffice is unavailable.

Covered:

* routing: ``.doc`` / ``.ppt`` / ``.xls`` are classified as legacy and
  extracted through the existing modern extractors after conversion;
* provenance: output keeps the ORIGINAL filename / extension and records
  ``source.format``, ``source.extension``, ``conversion.source_format`` and
  ``extraction.extractor`` — the conversion stays an internal detail;
* modern formats bypass LibreOffice entirely (no ``conversion`` block);
* unsupported formats stay untouched;
* conversion failure: the original file is preserved, no output is written,
  and the batch keeps processing other documents;
* the temporary conversion directory is cleaned up after the run.
"""

